function getZone(pos: PlayerPosition): PitchZone {
  if (pos === 'PO') return 'GK';
  if (pos === 'DFC' || pos === 'LI' || pos === 'LD') return 'DEF';
  if (pos === 'MCD' || pos === 'MC' || pos === 'MCO') return 'MID';
  return 'ATK';
}

function getTier(rating: number, explicitTier?: CardTier): CardTier {
  if (explicitTier) return explicitTier;
  if (rating >= 91) return 'toty';
  if (rating >= 85) return 'gold';
  if (rating >= 81) return 'silver';
  return 'bronze';
}

